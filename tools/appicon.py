#!/usr/bin/env python3
"""App icon (owner decision 32): the "J" of the title serif (Roboto Serif Title, SIL OFL; the typography role Retro's
titles fill, MERGE L-8) on the media black (color.global.backgroundDeep #000000), white glyph (color.global.textOnMedia).

Writes the iOS app and App Clip icon sets (one 1024 px image each, opaque), the Android adaptive launcher icon (black
background, white glyph inside the 66 dp safe zone, the same glyph as the themed-icon monochrome layer), the Android
status-bar icon (white on transparent, Material 3), the Play listing 512 px icon, and the option sheet the owner chose
from (design/icon/). The owner may replace any of these. Run from the repo root: python3 tools/appicon.py [A|B|C]
"""
import json
import os
import re
import shutil
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

FONT = "android/core/designsystem/src/main/res/font/roboto_serif_title.ttf"
LABEL_FONT = "android/core/designsystem/src/main/res/font/inter.ttf"
# Option: (background, glyph). A: media black (backgroundDeep / textOnMedia). B: the light page (background light /
# textPrimary light). C: the premium purple (color.global.premium) with white.
OPTIONS = {"A": ("#000000", "#FFFFFF"), "B": ("#FFFFFF", "#000000"), "C": ("#B02EC1", "#FFFFFF")}
GLYPH_HEIGHT = 0.56  # of the 1024 canvas; the adaptive foreground uses 0.36 of 108 dp (inside the 66 dp safe zone)
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n'
NOTE = ("<!-- App icon (owner decision 32, docs/OWNER_DECISIONS.md): the \"J\" of the title serif (Roboto Serif Title,\n"
        "     SIL OFL). Generated by tools/appicon.py; the owner may replace it. -->\n")


def glyph_path(canvas, frac):
    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    glyph = glyphs[font.getBestCmap()[ord("J")]]
    bounds = BoundsPen(glyphs)
    glyph.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    s = canvas * frac / (y1 - y0)
    tx = (canvas - (x1 - x0) * s) / 2 - x0 * s
    ty = (canvas + (y1 - y0) * s) / 2 + y0 * s
    pen = SVGPathPen(glyphs)
    glyph.draw(TransformPen(pen, (s, 0, 0, -s, tx, ty)))
    return re.sub(r"-?\d+\.\d+", lambda m: ("%.2f" % float(m.group())).rstrip("0").rstrip("."), pen.getCommands())


def render(canvas, bg, fg, supersample=4):
    big = canvas * supersample
    font = ImageFont.truetype(FONT, int(round(GLYPH_HEIGHT * big * 1000 / 720)))  # the J is 720 units tall
    left, top, right, bottom = font.getbbox("J")
    img = Image.new("RGB", (big, big), bg)
    ImageDraw.Draw(img).text(((big - (right - left)) / 2 - left, (big - (bottom - top)) / 2 - top), "J", font=font, fill=fg)
    return img.resize((canvas, canvas), Image.LANCZOS)


def vector(size, color, path):
    return (HEADER + NOTE + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
            f'    android:viewportWidth="{size}"\n    android:viewportHeight="{size}">\n'
            f'    <path\n        android:fillColor="{color}"\n        android:pathData="{path}" />\n</vector>\n')


def main():
    choice = sys.argv[1] if len(sys.argv) > 1 else "A"
    bg, fg = OPTIONS[choice]
    os.makedirs("design/icon", exist_ok=True)
    for key, (b, f) in OPTIONS.items():
        render(1024, b, f).save(f"design/icon/option_{key}.png")
    sheet = Image.new("RGB", (3 * 360 + 80, 440), "#E9E9EB")
    draw = ImageDraw.Draw(sheet)
    label = ImageFont.truetype(LABEL_FONT, 28)
    for i, key in enumerate(OPTIONS):
        icon = Image.open(f"design/icon/option_{key}.png").resize((300, 300), Image.LANCZOS)
        mask = Image.new("L", (300, 300), 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, 299, 299), radius=67, fill=255)
        sheet.paste(icon, (40 + i * 360, 40), mask)
        draw.text((190 + i * 360, 370), f"Option {key}", font=label, fill="#000000", anchor="mm")
    sheet.save("design/icon/options.png")

    chosen = render(1024, bg, fg)
    for catalog in ("ios/App/Resources/Assets.xcassets", "ios/AppClip/Resources/Assets.xcassets"):
        iconset = f"{catalog}/AppIcon.appiconset"
        os.makedirs(iconset, exist_ok=True)
        chosen.save(f"{iconset}/AppIcon.png")
        with open(f"{iconset}/Contents.json", "w") as out:
            json.dump({"images": [{"filename": "AppIcon.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"}],
                       "info": {"author": "xcode", "version": 1}}, out, indent=2)
            out.write("\n")
    with open("ios/AppClip/Resources/Assets.xcassets/Contents.json", "w") as out:
        json.dump({"info": {"author": "xcode", "version": 1}}, out, indent=2)
        out.write("\n")
    chosen.resize((512, 512), Image.LANCZOS).save("design/icon/play-icon-512.png")

    res = "android/app/src/main/res"
    for folder in ("mipmap-anydpi-v26", "drawable", "values"):
        os.makedirs(f"{res}/{folder}", exist_ok=True)
    adaptive = (HEADER + NOTE + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@color/ic_launcher_background" />\n'
                '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
                '    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n'
                '</adaptive-icon>\n')
    for name in ("ic_launcher", "ic_launcher_round"):
        with open(f"{res}/mipmap-anydpi-v26/{name}.xml", "w") as out:
            out.write(adaptive)
    with open(f"{res}/drawable/ic_launcher_foreground.xml", "w") as out:
        out.write(vector(108, fg, glyph_path(108, 0.36)))
    with open(f"{res}/values/ic_launcher_background.xml", "w") as out:
        out.write(HEADER + f'<resources>\n    <color name="ic_launcher_background">{bg}</color>\n</resources>\n')
    os.makedirs("android/core/push/src/main/res/drawable", exist_ok=True)
    with open("android/core/push/src/main/res/drawable/ic_stat_jolt.xml", "w") as out:
        out.write(vector(24, "#FFFFFFFF", glyph_path(24, 0.75)))
    print(f"app icon option {choice} written")


if __name__ == "__main__":
    main()
