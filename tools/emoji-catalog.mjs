#!/usr/bin/env node
// The reaction picker's emoji catalog (design/surfaces/chat.reactions.md §3), generated from Unicode's
// emoji keyboard data: every fully-qualified emoji of the RGI set (UTS #51 ED-27), in CLDR order, grouped by
// Unicode's standard groups (the "Component" group — bare skin-tone and hair swatches — left out), each
// skin-tone variant attached to the emoji it modifies.
//
//   node tools/emoji-catalog.mjs <emoji-test.txt>   generate both copies from Unicode's file
//   node tools/emoji-catalog.mjs --check            the two copies exist, are identical and parse
//
// Source: https://www.unicode.org/Public/17.0.0/emoji/emoji-test.txt (Unicode License v3,
// https://www.unicode.org/license.txt). The file itself is not committed.
//
// Output format (UTF-8, one entry per line, tab-separated):
//   # comment                       (hash and space: "#️⃣" starts with "#")
//   @<group name>                       a standard group, in Unicode's order
//   <emoji>\t<emoji version>\t<CLDR name>      an emoji shown in the grid
//   +<emoji>\t<emoji version>\t<CLDR name>     a skin-tone variant of the entry above (touch and hold)
//
// Outputs (the same bytes): ios/App/Resources/EmojiCatalog.txt (app bundle) and
// android/feature/social/src/main/res/raw/emoji_catalog.txt (raw resource). backend/tests reads the
// iOS copy to prove `private.is_emoji` accepts every sequence a picker can send.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUTS = ["ios/App/Resources/EmojiCatalog.txt", "android/feature/social/src/main/res/raw/emoji_catalog.txt"];
const SKIN_TONES = new Set([0x1f3fb, 0x1f3fc, 0x1f3fd, 0x1f3fe, 0x1f3ff]);
const LEFT_OUT_GROUP = "Component";

/** Parses emoji-test.txt into the catalog text. */
export function build(source) {
  const version = /^# Version: (.+)$/m.exec(source)?.[1]?.trim();
  if (!version) throw new Error("not an emoji-test.txt (no '# Version:' line)");
  const lines = [
    `# Generated by tools/emoji-catalog.mjs from Unicode emoji-test.txt ${version} (https://www.unicode.org/Public/${version}.0/emoji/emoji-test.txt). Do not edit.`,
    "# @group | emoji<TAB>emoji version<TAB>CLDR name | +skin-tone variant of the entry above",
  ];
  let group = null;
  let hasBase = false;
  for (const raw of source.split("\n")) {
    const groupMatch = /^# group: (.+)$/.exec(raw);
    if (groupMatch) {
      group = groupMatch[1].trim();
      hasBase = false;
      if (group !== LEFT_OUT_GROUP) lines.push(`@${group}`);
      continue;
    }
    if (!raw.trim() || raw.startsWith("#") || group === LEFT_OUT_GROUP) continue;
    // 1F44B 1F3FB ; fully-qualified # 👋🏻 E1.0 waving hand: light skin tone
    const m = /^([0-9A-F ]+);\s*([a-z-]+)\s*#\s*\S+\s+E([0-9.]+)\s+(.+)$/.exec(raw);
    if (!m) throw new Error(`unreadable line: ${raw}`);
    if (m[2] !== "fully-qualified") continue;
    const codePoints = m[1].trim().split(/\s+/).map((h) => parseInt(h, 16));
    const emoji = String.fromCodePoint(...codePoints);
    const isVariant = codePoints.some((c) => SKIN_TONES.has(c));
    if (isVariant && !hasBase) throw new Error(`skin-tone variant without a base: ${raw}`);
    lines.push(`${isVariant ? "+" : ""}${emoji}\t${m[3]}\t${m[4].trim()}`);
    if (!isVariant) hasBase = true;
  }
  return lines.join("\n") + "\n";
}

/** Reads the catalog text back: groups of entries with their variants (used by --check and the backend test). */
export function parse(text) {
  const groups = [];
  for (const line of text.split("\n")) {
    if (!line || line.startsWith("# ")) continue; // "#️⃣" is an emoji, "# " a comment
    if (line.startsWith("@")) {
      groups.push({ name: line.slice(1), entries: [] });
      continue;
    }
    const variant = line.startsWith("+");
    const [emoji, version, name] = (variant ? line.slice(1) : line).split("\t");
    if (!emoji || !version || !name) throw new Error(`malformed catalog line: ${line}`);
    const group = groups.at(-1);
    if (!group) throw new Error(`entry before the first group: ${line}`);
    if (variant) {
      const base = group.entries.at(-1);
      if (!base) throw new Error(`variant without a base: ${line}`);
      base.variants.push({ emoji, version, name });
    } else {
      group.entries.push({ emoji, version, name, variants: [] });
    }
  }
  return groups;
}

function main(argv) {
  if (argv[0] === "--check") {
    const texts = OUTPUTS.map((p) => fs.readFileSync(path.join(ROOT, p), "utf8"));
    if (texts.some((t) => t !== texts[0])) throw new Error(`${OUTPUTS.join(" and ")} differ: regenerate both`);
    const groups = parse(texts[0]);
    const count = groups.reduce((n, g) => n + g.entries.reduce((m, e) => m + 1 + e.variants.length, 0), 0);
    console.log(`emoji-catalog: ok (${groups.length} groups, ${count} emoji)`);
    return;
  }
  if (!argv[0]) throw new Error("usage: node tools/emoji-catalog.mjs <emoji-test.txt> | --check");
  const text = build(fs.readFileSync(argv[0], "utf8"));
  parse(text);
  for (const p of OUTPUTS) {
    fs.mkdirSync(path.dirname(path.join(ROOT, p)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, p), text);
  }
  console.log(`emoji-catalog: wrote ${OUTPUTS.join(", ")}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv.slice(2));
  } catch (e) {
    console.error(`emoji-catalog: ${e.message}`);
    process.exit(1);
  }
}
