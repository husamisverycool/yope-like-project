package app.feature.social.reactions

import android.content.Context
import android.graphics.Paint
import androidx.compose.runtime.Immutable
import androidx.core.content.edit
import androidx.core.graphics.PaintCompat
import app.designsystem.generated.Tokens
import app.feature.social.R

/** One emoji of the catalog: the sequence, the Emoji version that added it and Unicode's CLDR name. */
@Immutable
data class CatalogEmoji(val emoji: String, val version: String, val name: String)

/** An emoji shown in the grid and its skin-tone variants (touch and hold). */
@Immutable
data class CatalogEntry(val base: CatalogEmoji, val variants: List<CatalogEmoji> = emptyList()) {
    /** The base, then its variants: what touch and hold offers. */
    val choices: List<CatalogEmoji> get() = listOf(base) + variants
}

/** One of Unicode's standard groups ("Smileys & Emotion" … "Flags"); the picker shows the copy key in the same position. */
@Immutable
data class CatalogGroup(val name: String, val entries: List<CatalogEntry>)

/**
 * The reaction picker's emoji (design/surfaces/chat.reactions.md §3): every fully-qualified emoji of Unicode's RGI set in
 * CLDR order, grouped by Unicode's standard groups, skin-tone variants under the emoji they modify. Data: res/raw
 * emoji_catalog.txt, generated by tools/emoji-catalog.mjs from Unicode's emoji-test.txt (the same file ships in the iOS
 * app). Format: `@<group>`; `<emoji>\t<version>\t<name>`; a leading `+` marks a variant of the entry above; `# ` comments.
 */
@Immutable
data class EmojiCatalogData(val groups: List<CatalogGroup>) {
    /** Every emoji (bases and variants) with its name, for spoken labels. */
    val names: Map<String, String> by lazy {
        buildMap { groups.forEach { g -> g.entries.forEach { e -> e.choices.forEach { putIfAbsent(it.emoji, it.name) } } } }
    }

    /** The picker's search: base emoji whose name contains [query] (case-insensitive), in catalog order. */
    fun search(query: String): List<CatalogEntry> {
        val needle = query.trim()
        if (needle.isEmpty()) return emptyList()
        return groups.flatMap { it.entries }.filter { it.base.name.contains(needle, ignoreCase = true) }
    }

    /** The entry whose choices hold [emoji] (a recently used variant finds its base). */
    fun entryContaining(emoji: String): CatalogEntry? =
        groups.firstNotNullOfOrNull { g -> g.entries.firstOrNull { e -> e.choices.any { it.emoji == emoji } } }

    /** Without the emoji [isSupported] rejects: an unsupported base leaves with its entry, unsupported variants leave it. */
    fun filtered(isSupported: (String) -> Boolean): EmojiCatalogData = EmojiCatalogData(
        groups.map { g ->
            CatalogGroup(g.name, g.entries.mapNotNull { e -> if (!isSupported(e.base.emoji)) null else e.copy(variants = e.variants.filter { isSupported(it.emoji) }) })
        },
    )

    companion object {
        /** Reads the catalog text; malformed lines are skipped, a variant before any entry is dropped. */
        fun parse(text: String): EmojiCatalogData {
            val groups = ArrayList<CatalogGroup>()
            var name: String? = null
            val entries = ArrayList<CatalogEntry>()
            var base: CatalogEmoji? = null
            val variants = ArrayList<CatalogEmoji>()
            fun closeEntry() {
                base?.let { entries += CatalogEntry(it, variants.toList()) }
                base = null
                variants.clear()
            }
            fun closeGroup() {
                closeEntry()
                name?.let { groups += CatalogGroup(it, entries.toList()) }
                entries.clear()
            }
            for (line in text.lineSequence()) {
                if (line.isEmpty() || line.startsWith("# ")) continue // "#️⃣" is an emoji, "# " a comment
                if (line.startsWith("@")) {
                    closeGroup()
                    name = line.substring(1)
                    continue
                }
                val variant = line.startsWith("+")
                val fields = (if (variant) line.substring(1) else line).split('\t')
                if (name == null || fields.size != 3 || fields[0].isEmpty() || fields[2].isEmpty()) continue
                val emoji = CatalogEmoji(fields[0], fields[1], fields[2])
                if (variant) {
                    if (base != null) variants += emoji
                } else {
                    closeEntry()
                    base = emoji
                }
            }
            closeGroup()
            return EmojiCatalogData(groups)
        }
    }
}

/**
 * The picker's data on this device: the bundled catalog without the emoji the system font cannot draw (newer than the
 * font they would draw as tofu — left out, as the platform emoji picker does), and the person's recently used emoji
 * (kept per device, "Frequently Used").
 */
object EmojiCatalog {
    private const val PREFS = "social_reactions"
    private const val RECENT = "recent"
    private const val SEPARATOR = "\u0000"

    /** How many recently used emoji are kept: one picker row (`chat.reactions.count.pickerColumns`). */
    private val recentMax get() = Tokens.Counts.chatReactionsCountPickerColumns

    fun recent(context: Context): List<String> =
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(RECENT, null)?.split(SEPARATOR)?.filter { it.isNotEmpty() }.orEmpty()

    fun remember(context: Context, emoji: String) {
        val list = (listOf(emoji) + recent(context).filter { it != emoji }).take(recentMax)
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit { putString(RECENT, list.joinToString(SEPARATOR)) }
    }

    @Volatile private var bundled: EmojiCatalogData? = null
    @Volatile private var shown: EmojiCatalogData? = null

    /** The names of the bundled catalog once it has been read (null before): `EmojiNames` speaks CLDR names from then on. */
    val loadedNames: Map<String, String>? get() = bundled?.names

    /** Every entry of the bundled file (names, lookups); empty when it cannot be read. */
    fun bundled(context: Context): EmojiCatalogData = bundled ?: synchronized(this) {
        bundled ?: runCatching {
            context.resources.openRawResource(R.raw.emoji_catalog).bufferedReader(Charsets.UTF_8).use { EmojiCatalogData.parse(it.readText()) }
        }.getOrDefault(EmojiCatalogData(emptyList())).also { bundled = it }
    }

    /** The device catalog when it has been computed already (null before). */
    val shownIfReady: EmojiCatalogData? get() = shown

    /** The catalog this device can draw (computed once; call off the main thread the first time). */
    fun shown(context: Context): EmojiCatalogData = shown ?: synchronized(this) {
        shown ?: run {
            val paint = Paint()
            bundled(context).filtered { PaintCompat.hasGlyph(paint, it) }
        }.also { shown = it }
    }
}
