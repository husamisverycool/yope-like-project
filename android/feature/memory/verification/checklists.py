#!/usr/bin/env python3
"""Verification checklists for the memory group's Android screens (docs/SCREENS_BRIEF.md rule 8).

Reads our Roborazzi renders (android/feature/memory/src/test/snapshots, 393 x 852 dp at 2 px/dp, Robolectric
native graphics, Roboto, Reduce Motion off), measures them, looks every token up in design/tokens/*.json
(value + evidence) and writes design/verification/<surface>.android.md. Side-by-sides
(<surface>.android.png) come from tools/sidebyside.py (see PAIRS below and `--images`).

Usage: python3 -I android/feature/memory/verification/checklists.py [--images]
"""
import glob
import json
import os
import subprocess
import sys

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
SNAP = os.path.join(ROOT, "android/feature/memory/src/test/snapshots")
REF = os.path.join(ROOT, "references/auto")
OUT = os.path.join(ROOT, "design/verification")
PX = 2.0  # px per dp in the renders (xhdpi)
TOL = 1.0  # dp: pixel rounding at 2 px/dp plus anti-aliased edges

TOKENS = {}
for f in glob.glob(os.path.join(ROOT, "design/tokens/*.json")):
    TOKENS.update(json.load(open(f)).get("tokens", {}))


def tok(name):
    t = TOKENS.get(name)
    if t is None:
        return "?", "", "missing"
    v = t.get("value")
    if isinstance(v, dict):
        v = "; ".join(f"{k}: {x}" for k, x in v.items())
    return str(v), str(t.get("evidence", ""))[:110], t.get("level", "")


_cache = {}


def img(path):
    if path not in _cache:
        _cache[path] = Image.open(os.path.join(SNAP, path)).convert("RGB")
    return _cache[path]


def hexc(c):
    return "#%02X%02X%02X" % c


def bbox(im, pred, region=None, step=1):
    x0, y0, x1, y1 = region or (0, 0, im.width, im.height)
    xs, ys = [], []
    for y in range(y0, y1, step):
        for x in range(x0, x1, step):
            if pred(im.getpixel((x, y))):
                xs.append(x)
                ys.append(y)
    return (min(xs), min(ys), max(xs), max(ys)) if xs else None


def runs(im, x, pred, y0=0, y1=None):
    y1 = y1 or im.height
    out, start = [], None
    for y in range(y0, y1):
        if pred(im.getpixel((x, y))):
            if start is None:
                start = y
        elif start is not None:
            out.append((start, y - 1))
            start = None
    if start is not None:
        out.append((start, y1 - 1))
    return out


def near(c, ref, d=4):
    return all(abs(a - b) <= d for a, b in zip(c, ref))


LIME = (0xCD, 0xFD, 0x07)
WHITE = (255, 255, 255)
BLACK = (0, 0, 0)


class Sheet:
    def __init__(self, surface, title, renders, sbs_note):
        self.surface, self.title, self.renders, self.sbs_note = surface, title, renders, sbs_note
        self.sections = []
        self.counts = {}

    def section(self, name):
        self.sections.append((name, []))

    def add(self, status, token, expected, ours, note="", evidence=None):
        if evidence is None:
            evidence = tok(token.split(" ")[0].strip("`"))[1] if token.startswith("`") else ""
        self.sections[-1][1].append((status, token, expected, ours, evidence, note))
        self.counts[status] = self.counts.get(status, 0) + 1

    def measure(self, token, expected, measured, note=""):
        """A dp measurement compared with the token value."""
        ok = measured is not None and abs(measured - float(expected)) <= TOL
        self.add("match" if ok else "not matched", f"`{token}`", f"{expected}", f"{measured:g}" if measured is not None else "—", note)

    def colour(self, token, measured_rgb, note=""):
        v = tok(token)[0].upper()
        ok = v.startswith("#") and v[:7] == hexc(measured_rgb)
        self.add("match" if ok else "not matched", f"`{token}`", v, hexc(measured_rgb), note)

    def from_token(self, token, ours, note=""):
        self.add("match (token)", f"`{token}`", tok(token)[0], ours, note)

    def write(self):
        total = sum(self.counts.values())
        order = ["match", "match (token)", "approx", "not matched", "BLOCKED", "worker"]
        summary = ", ".join(f"{self.counts[k]} {k}" for k in order if self.counts.get(k))
        lines = [
            f"# Verification — `{self.surface}` (Android)",
            "",
            f"{self.title}",
            "",
            "Generated by `android/feature/memory/verification/checklists.py` from the Robolectric renders "
            "(`./gradlew :feature:memory:recordRoborazziDebug`, debug build, 393 × 852 dp at 2 px/dp, Roboto, Reduce Motion "
            "off, no system-bar insets) — measured values are dp (±1 dp: pixel rounding and anti-aliasing). Rows marked "
            "*match (token)* are drawn straight from the generated constant (no pixel measurement); rows marked *worker* are "
            "values the worker burns into a video, which the app never draws. Reference values and "
            "evidence come from `design/tokens/*.json`. Test images are sample photos (`fixtures/photos/`, Unsplash License; no reference content).",
            "",
            f"Side by side: [`{self.surface}.android.png`]({self.surface}.android.png) — {self.sbs_note}",
            "",
            f"Renders: {', '.join('`' + r + '`' for r in self.renders)}",
            "",
            f"**Result: {total} checks — {summary}.**",
            "",
        ]
        for name, rows in self.sections:
            lines += [f"## {name}", "", "| status | token | expected (token) | ours | reference evidence | note |", "|---|---|---|---|---|---|"]
            for st, t, e, o, ev, n in rows:
                cell = lambda s: str(s).replace("|", "/").replace("\n", " ")
                lines.append(f"| {st} | {cell(t)} | {cell(e)} | {cell(o)} | {cell(ev)} | {cell(n)} |")
            lines.append("")
        path = os.path.join(OUT, f"{self.surface}.android.md")
        open(path, "w").write("\n".join(lines) + self.extra)
        print(path, total, summary)

    extra = ""


