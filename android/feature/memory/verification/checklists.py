def images(tmp):
    os.makedirs(tmp, exist_ok=True)
    for surface, rows in PAIRS.items():
        parts = []
        for i, (ours, ref, rc, oc, title) in enumerate(rows):
            out = os.path.join(tmp, f"{surface}-{i}.png")
            cmd = [sys.executable, os.path.join(ROOT, "tools/sidebyside.py"), out, os.path.join(SNAP, ours), os.path.join(REF, ref), "--title", f"{surface}: {title}", "--height", "600" if oc else "1200"]
            if rc:
                cmd += ["--ref-crop", rc]
            if oc:
                cmd += ["--ours-crop", oc]
            subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
            parts.append(Image.open(out))
        sheet = Image.new("RGB", (max(p.width for p in parts), sum(p.height for p in parts)), (128, 128, 128))
        y = 0
        for p in parts:
            sheet.paste(p, (0, y))
            y += p.height
        sheet.save(os.path.join(OUT, f"{surface}.android.png"))


