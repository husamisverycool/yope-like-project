import Foundation

/// A typed database id (`uuid`, docs/API.md §1: a lowercase string).
///
/// The phantom `Entity` keeps a post id from being passed where a group id is expected. Values
/// are normalized to lowercase because storage paths and RLS path checks compare the text form
/// (`u/<uid>/<media_id>/…` must match `media.id::text`, which Postgres prints in lowercase).
public struct Identifier<Entity>: RawRepresentable, Hashable, Comparable, Codable, Sendable, CustomStringConvertible {
    public let rawValue: String

    public init(rawValue: String) {
        self.rawValue = rawValue.lowercased()
    }

    public init(_ rawValue: String) {
        self.init(rawValue: rawValue)
    }

    public init(_ uuid: UUID) {
        self.init(rawValue: uuid.uuidString)
    }

    /// A new random (v4) id. Only `media.id` is generated by the client (docs/API.md §1).
    public static func generate() -> Self {
        Self(UUID())
    }

    /// The id as a `UUID`, when it is one.
    public var uuid: UUID? { UUID(uuidString: rawValue) }

    public var description: String { rawValue }

    public static func < (lhs: Self, rhs: Self) -> Bool { lhs.rawValue < rhs.rawValue }

    public init(from decoder: Decoder) throws {
        let container = try decoder.singleValueContainer()
        self.init(rawValue: try container.decode(String.self))
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.singleValueContainer()
        try container.encode(rawValue)
    }
}

public typealias UserID = Identifier<Profile>
public typealias GroupID = Identifier<PhotoGroup>
public typealias InviteID = Identifier<GroupInvite>
public typealias MediaID = Identifier<Media>
public typealias PostID = Identifier<Post>
public typealias MessageID = Identifier<Message>
public typealias InvitationID = Identifier<DailyInvitation>
public typealias CollageID = Identifier<Collage>
public typealias RecapID = Identifier<WeeklyRecap>
public typealias AlbumID = Identifier<Album>
public typealias TributeRequestID = Identifier<TributeRequest>
public typealias TributeContributionID = Identifier<TributeContribution>
public typealias TributeID = Identifier<Tribute>
public typealias YearStoryID = Identifier<YearStory>
public typealias DeviceID = Identifier<Device>
public typealias ReportID = Identifier<ReportRecord>
